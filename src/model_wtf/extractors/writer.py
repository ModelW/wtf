"""Turn a :class:`Surface` into the unit's ``.gen.yaml`` files.

One writer for every source of facts -- the Django extractor, the
SvelteKit extractor, the agent's ``discover`` (which is converted into a
Surface first) -- so the generated files always have the same shape and
ids whatever produced them. Output is deterministic (sorted keys, no
timestamps) and only ever touches ``*.gen.yaml``: human twins, ledgers
and findings are never read or written here.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import TYPE_CHECKING, Any

import yaml

from model_wtf.knowledge.loader import load_knowledge

if TYPE_CHECKING:
    from pathlib import Path

    from model_wtf.extractors.surface import (
        Egress,
        Entrypoint,
        Storage,
        StorageField,
        Surface,
        Task,
    )
    from model_wtf.knowledge.schemas import Egress as CatalogueEgress


def gen_header(twin: str) -> str:
    """The banner every generated file starts with."""
    return f"# GENERATED by model-wtf \u2014 do not edit; edit {twin}\n"


@dataclass(slots=True)
class WriteReport:
    """Files the writer produced (unchanged files are listed too)."""

    written: list[Path] = field(default_factory=list)
    changed: list[Path] = field(default_factory=list)


def write_surface(
    folder: Path,
    surface: Surface,
    *,
    by: str = "extractor",
    source_sha: str | None = None,
) -> WriteReport:
    """Write ``elements/unit.gen.yaml``, ``data/*.gen.yaml``, ``recipients/*.gen.yaml``.

    Parameters
    ----------
    folder
        The unit's compliance folder.
    surface
        Facts about the unit.
    by
        ``extractor`` or ``agent`` -- who produced the facts.
    source_sha
        Hash of the unit's source, so ``auto`` can skip re-discovery when
        nothing changed.
    """
    report = WriteReport()
    catalogue = load_knowledge().egress

    unit: dict[str, Any] = {
        "by": by,
        "stack": sorted(surface.stack),
        "entrypoints": [
            _entrypoint(e) for e in sorted(surface.entrypoints, key=lambda e: e.id)
        ],
        "tasks": [_task(t) for t in sorted(surface.tasks, key=lambda t: t.id)],
        "config": [
            c.model_dump(mode="json", exclude_none=True)
            for c in sorted(surface.config, key=lambda c: c.key)
        ],
        "controls": dict(sorted(surface.controls.items())),
    }
    if source_sha is not None:
        unit["source_sha"] = source_sha
    _write(folder / "elements" / "unit.gen.yaml", unit, "(no twin: unit facts)", report)

    for storage in surface.storage:
        object_id = data_object_id(storage)
        _write(
            folder / "data" / f"{object_id}.gen.yaml",
            _data_object(storage, by),
            f"{object_id}.yaml",
            report,
        )

    for egress in surface.egress:
        slug = egress_slug(egress, catalogue)
        _write(
            folder / "recipients" / f"{slug}.gen.yaml",
            _recipient(egress, slug, catalogue.get(slug), surface.unit, by),
            f"{slug}.yaml",
            report,
        )
    return report


