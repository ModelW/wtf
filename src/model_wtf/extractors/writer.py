# Ids
# ---------------------------------------------------------------------------


def data_object_id(storage: Storage) -> str:
    """``store:people.User`` -> ``people.user`` (data object id = file name)."""
    return f"{storage.app_label}.{storage.model}".lower()


def egress_slug(egress: Egress, catalogue: dict[str, CatalogueEgress]) -> str:
    """Catalogue slug when the egress matches an entry, else a derived one.

    Matching is by SDK package (``egress:sdk:sentry_sdk``), host
    (``egress:host:o123.ingest.sentry.io``: any catalogue host that is a
    suffix) or credential env key.
    """
    kind, _, value = egress.id.partition(":")[2].partition(":")
    value_norm = value.lower().replace("_", "-")
    for slug, entry in catalogue.items():
        packages = {p.lower().replace("_", "-") for p in entry.detection.packages}
        if kind == "sdk" and value_norm in packages:
            return slug
        if kind == "host" and any(
            value.lower() == h.lower() or value.lower().endswith("." + h.lower())
            for h in entry.detection.hosts
        ):
            return slug
        if set(egress.credential_keys) & set(entry.detection.env):
            return slug
    if kind == "host":
        parts = value.lower().split(".")
        base = parts[-2] if len(parts) >= 2 else parts[0]
        return base.replace("_", "-")
    return value_norm or "unknown"


