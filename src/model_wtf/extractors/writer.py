def _entrypoint(entry: Entrypoint) -> dict[str, Any]:
    data: dict[str, Any] = entry.model_dump(
        mode="json", exclude_none=True, exclude_defaults=True
    )
    data.update({"id": entry.id, "path": entry.path})
    return data


def _task(task: Task) -> dict[str, Any]:
    data: dict[str, Any] = task.model_dump(
        mode="json", exclude_none=True, exclude_defaults=True
    )
    data["id"] = task.id
    return data


def _field(f: StorageField) -> tuple[dict[str, Any], bool]:
    """One field's ``.gen`` spec and whether it smells of personal data."""
    spec: dict[str, Any] = {"type": f.type}
    pii = False
    if f.pii_hints:
        order = ("low", "medium", "high")
        best = max(f.pii_hints, key=lambda h: order.index(h.confidence))
        spec["suggested"] = best.item
        spec["confidence"] = best.confidence
        pii = best.item != "none"
    if f.opaque:
        spec["opaque"] = True
        pii = True  # unknown contents are a PII risk until classified
    if f.candidate_contents:
        spec["candidate_contents"] = sorted({c.name for c in f.candidate_contents})
    if f.fk_target:
        spec["fk_target"] = f.fk_target
        if f.on_delete:
            spec["on_delete"] = f.on_delete
    for flag in ("null", "unique", "primary_key"):
        if getattr(f, flag):
            spec[flag] = True
    spec.update(
        {k: v for k, v in (f.model_extra or {}).items() if v not in (None, [], {})}
    )
    return spec, pii


def _data_object(storage: Storage, by: str) -> dict[str, Any]:
    fields: dict[str, Any] = {}
    pii = False
    for f in storage.fields:
        fields[f.name], field_pii = _field(f)
        pii = pii or field_pii
    data: dict[str, Any] = {
        "by": by,
        "sources": [storage.id],
        "fields": fields,
        "lifecycle": storage.lifecycle.model_dump(
            mode="json", exclude_none=True, exclude_defaults=True
        ),
        "pii_suspected": pii,
    }
    if storage.shadow_store:
        data["shadow_store"] = True
    if storage.database:
        data["database"] = storage.database
    if storage.provenance:
        data["provenance"] = storage.provenance
    return data


def _recipient(
    egress: Egress, slug: str, entry: CatalogueEgress | None, unit: str, by: str
) -> dict[str, Any]:
    kind, _, value = egress.id.partition(":")[2].partition(":")
    detection: dict[str, Any] = {
        "packages": [],
        "hosts": [],
        "env": sorted(egress.credential_keys),
    }
    if kind == "sdk":
        detection["packages"] = [value]
    elif kind == "host":
        detection["hosts"] = [value]
    data: dict[str, Any] = {
        "by": by,
        "detection": detection,
        "units": [unit],
        "provenance": sorted(egress.provenance),
    }
    if egress.facts:
        data["facts"] = dict(sorted(egress.facts.items()))
    if entry is not None:
        data["suggested"] = {
            "name": entry.name,
            "kind": entry.kind,
            **(
                {"third_country": entry.default_third_country}
                if entry.default_third_country
                else {}
            ),
            **({"sink": True} if entry.sink else {}),
        }
    return data


def _write(path: Path, data: dict[str, Any], twin: str, report: WriteReport) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    text = gen_header(twin) + yaml.safe_dump(
        data, sort_keys=True, allow_unicode=True, width=100
    )
    if not path.is_file() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8")
        report.changed.append(path)
    report.written.append(path)
