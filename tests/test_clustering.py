def _seed(make_repo: MakeRepo) -> tuple[Path, object]:
    root = make_repo(snow=SNOW, dirs=("api/compliance",))
    surface = load_surface_file(SURFACE)
    write_surface(root / "api/compliance", surface)
    write_clusters(root / "api/compliance", surface)
    return root / "api/compliance", surface


def test_remove_directive_on_twin(make_repo: MakeRepo) -> None:
    folder, surface = _seed(make_repo)
    (folder / "processing" / "people.yaml").write_text(
        "purpose: Authenticate users and serve their profile.\nlawful_basis: contract\n"
        "data_subject_categories: []\nmembers:\n  remove: [http:GET:/back/api/me/]\n"
    )

    report = write_clusters(folder, surface)  # type: ignore[arg-type]

    assert "http:GET:/back/api/me/" not in _gen(folder, "people")["members"]
    assert report.uncovered == ["http:GET:/back/api/me/"]


def test_split_off_activity_claims_members(make_repo: MakeRepo) -> None:
    folder, surface = _seed(make_repo)
    (folder / "processing" / "auth.yaml").write_text(
        "purpose: Log users in and out of the platform securely.\n"
        "lawful_basis: contract\n"
        "data_subject_categories: []\n"
        "members: [http:POST:/back/api/auth/login/, http:POST:/back/api/auth/logout/]\n"
    )

    report = write_clusters(folder, surface)  # type: ignore[arg-type]

    assert report.uncovered == []
    assert _gen(folder, "people")["members"] == [
        "http:GET:/back/api/me/",
        "task:people.tasks.purge_inactive",
    ]
    auth = _gen(folder, "auth")
    assert auth["members"] == [
        "http:POST:/back/api/auth/login/",
        "http:POST:/back/api/auth/logout/",
    ]
    assert auth["human_split"] is True
    directives = read_human_members(folder)
    assert directives["auth"].explicit == frozenset(auth["members"])


def test_add_directive_moves_member(make_repo: MakeRepo) -> None:
    folder, surface = _seed(make_repo)
    (folder / "processing" / "cms.yaml").write_text(
        "purpose: Publish and preview marketing pages for everyone.\n"
        "lawful_basis: legitimate_interest\n"
        "data_subject_categories: []\nmembers:\n  add: [http:GET:/back/health/]\n"
    )

    write_clusters(folder, surface)  # type: ignore[arg-type]

    assert "http:GET:/back/health/" in _gen(folder, "cms")["members"]
    assert not (folder / "processing" / "health.gen.yaml").exists() or (
        _gen(folder, "health")["members"] == []
    )


def test_uncovered_member_becomes_a_finding(make_repo: MakeRepo) -> None:
    folder, surface = _seed(make_repo)
    root = folder.parent.parent
    (folder / "actors").mkdir(exist_ok=True)
    (folder / "actors" / "users.yaml").write_text("name: Users\n")
    (folder / "processing" / "people.yaml").write_text(
        "purpose: Authenticate users and serve their own profile data.\n"
        "lawful_basis: contract\ndata_subject_categories: [users]\n"
        "members:\n  remove: [http:GET:/back/api/me/]\n"
    )
    report = write_clusters(folder, surface)  # type: ignore[arg-type]
    (folder / "elements").mkdir(exist_ok=True)
    (folder / "elements" / "coverage.gen.yaml").write_text(
        yaml.safe_dump({"by": "extractor", "uncovered_members": report.uncovered})
    )

    check = run_check(root, strict=False)

    assert check.exit_code is ExitCode.FINDINGS
    coverage = [
        d
        for d in check.diagnostics
        if d.code == "GDPR-ACTIVITY-COVERAGE" and d.element == "activity.people"
    ]
    assert coverage
    assert coverage[0].finding_id is not None

    # Claim it back: the gate passes on the next run.
    (folder / "processing" / "me.yaml").write_text(
        "purpose: Serve the authenticated user their own profile data.\n"
        "lawful_basis: contract\ndata_subject_categories: [users]\n"
        "members: [http:GET:/back/api/me/]\n"
    )
    report = write_clusters(folder, surface)  # type: ignore[arg-type]
    (folder / "elements" / "coverage.gen.yaml").write_text(
        yaml.safe_dump({"by": "extractor", "uncovered_members": report.uncovered})
    )
    check = run_check(root, strict=False)
    people_ledger = yaml.safe_load(
        (folder / "elements" / "activity.people.yaml").read_text()
    )
    assert people_ledger["GDPR-ACTIVITY-COVERAGE"]["status"] == "ok"
    # Undeclared gen-only clusters (cms, health) still block, saying why.
    cms_ledger = yaml.safe_load((folder / "elements" / "activity.cms.yaml").read_text())
    assert list(cms_ledger) == ["GDPR-PURPOSE"]
    assert cms_ledger["GDPR-PURPOSE"]["staged_because"] == "declaration missing"
    assert check.exit_code is ExitCode.FINDINGS


def test_members_key_is_schema_valid(make_repo: MakeRepo) -> None:
    root = make_repo(
        snow=SNOW,
        files={
            "api/compliance/actors/users.yaml": "name: Users\n",
            "api/compliance/processing/a.yaml": (
                "purpose: Something specific enough to pass the purpose gate here.\n"
                "lawful_basis: contract\ndata_subject_categories: [users]\n"
                "members: {add: [x], remove: [y]}\n"
            ),
            "api/compliance/processing/b.yaml": (
                "purpose: Something specific enough to pass the purpose gate here.\n"
                "lawful_basis: contract\ndata_subject_categories: [users]\n"
                "members: [x]\n"
            ),
        },
    )
    report = run_check(root, strict=False)
    assert not any(d.severity is Severity.ERROR for d in report.diagnostics), (
        report.diagnostics
    )
