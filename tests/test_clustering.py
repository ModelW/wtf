SURFACE = Path(__file__).parent / "eval" / "surfaces" / "template-api.surface.json"
SNOW = "images:\n  - id: api\n    context: api\n    compliance: compliance\n"


def _gen(folder: Path, name: str) -> dict[str, object]:
    return yaml.safe_load((folder / "processing" / f"{name}.gen.yaml").read_text())


def test_app_of_precedence() -> None:
    assert (
        app_of(
            Entrypoint(id="x", path="/h/", tags=["health"], view="apps.people.api.x")
        )
        == "health"
    )
    assert (
        app_of(
            Entrypoint(id="x", path="/p/", tags=["cms-preview"], view="apps.cms.api.p")
        )
        == "cms"
    )
    assert (
        app_of(Entrypoint(id="x", path="/", view="apps.people.api.login")) == "people"
    )
    assert app_of(Entrypoint(id="x", path="/", view="billing.views.pay")) == "billing"
    assert app_of(Entrypoint(id="x", path="/", namespace="shop:cart")) == "shop"
    assert (
        app_of(Entrypoint(id="http:GET:/back/api/orders/", path="/back/api/orders/"))
        == "orders"
    )


def test_default_clusters_from_template_surface(make_repo: MakeRepo) -> None:
    root = make_repo(snow=SNOW, dirs=("api/compliance",))
    folder = root / "api/compliance"
    surface = load_surface_file(SURFACE)
    write_surface(folder, surface)

    report = write_clusters(folder, surface)

    assert report.uncovered == []
    assert sorted(p.name for p in report.written) == [
        "cms.gen.yaml",
        "health.gen.yaml",
        "people.gen.yaml",
    ]
    people = _gen(folder, "people")
    assert people["members"] == [
        "http:GET:/back/api/me/",
        "http:POST:/back/api/auth/login/",
        "http:POST:/back/api/auth/logout/",
        "task:people.tasks.purge_inactive",
    ]
    assert people["data_objects"] == {"people.user": ["read", "write"]}
    cms = _gen(folder, "cms")
    assert cms["members"] == [
        "http:GET:/back/api/pages/",
        "http:GET:/back/api/preview/",
    ]
    assert cms["data_objects"] == {"cms.homepage": ["read"]}
    assert (
        "digitalocean-spaces" not in cms["suggested_recipients"]
    )  # settings.py egress, no app
    health = _gen(folder, "health")
    assert health["members"] == ["http:GET:/back/health/"]
    assert health["data_objects"] == {}
    for text in ((folder / "processing" / n).read_text() for n in ("people.gen.yaml",)):
        assert text.startswith(
            "# GENERATED by model-wtf \u2014 do not edit; edit people.yaml"
        )

    # Idempotent.
    before = {p: p.read_text() for p in (folder / "processing").glob("*.gen.yaml")}
    write_clusters(folder, surface)
    assert {
        p: p.read_text() for p in (folder / "processing").glob("*.gen.yaml")
    } == before


def test_egress_attributed_by_provenance_folder(make_repo: MakeRepo) -> None:
    root = make_repo(snow=SNOW, dirs=("api/compliance",))
    surface = parse_surface(
        {
            "schema": SCHEMA_ID,
            "unit": "api",
            "entrypoints": [
                {
                    "id": "http:POST:/pay/",
                    "path": "/pay/",
                    "view": "apps.billing.api.pay",
                    "provenance": "apps/billing/api.py:10",
                }
            ],
            "egress": [
                {"id": "egress:sdk:stripe", "provenance": ["apps/billing/api.py:3"]}
            ],
        }
    )
    write_clusters(root / "api/compliance", surface)
    billing = _gen(root / "api/compliance", "billing")
    assert billing["egress"] == ["stripe"]
    assert billing["suggested_recipients"] == ["stripe"]


def test_related_activities_when_model_is_shared(make_repo: MakeRepo) -> None:
    root = make_repo(snow=SNOW, dirs=("api/compliance",))
    surface = parse_surface(
        {
            "schema": SCHEMA_ID,
            "unit": "api",
            "storage": [
                {"id": "store:people.User", "app_label": "people", "model": "User"}
            ],
            "entrypoints": [
                {
                    "id": "http:GET:/me/",
                    "path": "/me/",
                    "view": "apps.people.api.me",
                    "models_read": ["store:people.User"],
                },
                {
                    "id": "http:GET:/orders/",
                    "path": "/orders/",
                    "view": "apps.shop.api.orders",
                    "models_read": ["store:people.User"],
                },
            ],
        }
    )
    write_clusters(root / "api/compliance", surface)
    assert _gen(root / "api/compliance", "people")["related_activities"] == ["shop"]
    assert _gen(root / "api/compliance", "shop")["related_activities"] == ["people"]


